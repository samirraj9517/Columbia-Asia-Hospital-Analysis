-- 15.	Identify the top 5 doctors who generated the most revenue but had the fewest patients. (SQL)
USE hospital_analytics;
SELECT
    doctor_id,
    doctor_name,
    SUM(total_bill) AS total_revenue,
    COUNT(DISTINCT patient_id) AS patient_count
FROM doctor_patients
GROUP BY
    doctor_id,
    doctor_name
ORDER BY
    total_revenue DESC,
    patient_count ASC
LIMIT 5;

-- 16.	Find the department where the average waiting time has decreased over three consecutive months. (SQL)
USE hospital_analytics;
WITH Monthly_Wait AS (
    SELECT
        Department_Referral AS Department,
        YEAR(`Date`) AS Visit_Year,
        MONTH(`Date`) AS Visit_Month,
        ROUND(AVG(Patient_Waittime), 2) AS Avg_Waiting_Time
    FROM hospital_er
    WHERE `Date` IS NOT NULL
      AND Department_Referral IS NOT NULL
      AND Patient_Waittime IS NOT NULL
    GROUP BY
        Department_Referral,
        YEAR(`Date`),
        MONTH(`Date`)
),

Compare_Wait AS (
    SELECT
        Department,
        Visit_Year,
        Visit_Month,
        Avg_Waiting_Time,

        LAG(Avg_Waiting_Time, 1) OVER (
            PARTITION BY Department
            ORDER BY Visit_Year, Visit_Month
        ) AS Previous_Month_Wait,

        LAG(Avg_Waiting_Time, 2) OVER (
            PARTITION BY Department
            ORDER BY Visit_Year, Visit_Month
        ) AS Two_Months_Ago_Wait

    FROM Monthly_Wait
)

SELECT
    Department,
    Visit_Year,
    Visit_Month,
    Two_Months_Ago_Wait,
    Previous_Month_Wait,
    Avg_Waiting_Time
FROM Compare_Wait
WHERE Avg_Waiting_Time < Previous_Month_Wait
  AND Previous_Month_Wait < Two_Months_Ago_Wait
ORDER BY
    Department,
    Visit_Year,
    Visit_Month;


-- 17.	Determine the ratio of male to female patients for each doctor and rank the doctors based on this ratio. (SQL)
USE hospital_analytics;
    WITH Doctor_Gender_Count AS (
    SELECT
        doctor_id,
        doctor_name,
        SUM(CASE
                WHEN patient_gender = 'Male' THEN 1
                ELSE 0
            END) AS Male_Patients,
        SUM(CASE
                WHEN patient_gender = 'Female' THEN 1
                ELSE 0
            END) AS female_patients
    FROM patient_complete_data
    GROUP BY doctor_id, doctor_name
)

SELECT
    doctor_id,
    doctor_name,
    male_patients,
    female_patients,
    ROUND(
        male_patients / NULLIF(female_patients, 0),
        2
    ) AS male_female_ratio,
    RANK() OVER (
        ORDER BY male_patients / NULLIF(female_patients, 0) DESC
    ) AS doctor_rank
FROM doctor_gender_count
ORDER BY doctor_rank;


-- 18.	Calculate the average satisfaction score of patients for each doctor based on their visits. (SQL)
USE hospital_analytics;
SELECT
    doctor_id,
    doctor_name,
    ROUND(AVG(`patient_sat_score`), 2) AS Average_Satisfaction_Score
FROM patient_complete_data
WHERE `patient_sat_score` IS NOT NULL
GROUP BY doctor_id, doctor_name
ORDER BY Average_Satisfaction_Score DESC;


-- 19.	Find doctors who have treated patients from different races and calculate the diversity of their patient base. (SQL)
USE hospital_analytics;

SELECT
    doctor_name,
    COUNT(DISTINCT patient_race) AS Total_Races,
    COUNT(DISTINCT patient_id) AS Total_Patients,
    GROUP_CONCAT(
        DISTINCT patient_race
        ORDER BY patient_race
        SEPARATOR ', '
    ) AS Patient_Races
FROM patient_complete_data
WHERE doctor_name IS NOT NULL
  AND patient_race IS NOT NULL
GROUP BY doctor_id, doctor_name
HAVING COUNT(DISTINCT patient_race) > 1
ORDER BY Total_Races DESC, Total_Patients DESC;


-- 20.	Calculate the ratio of total bills generated by male patients to female patients for each department. (SQL)
USE hospital_analytics;

SELECT
    er_department_referral AS Department,

    SUM(CASE
        WHEN patient_gender = 'Male' THEN total_bill
        ELSE 0
    END) AS Male_Total_Bill,

    SUM(CASE
        WHEN patient_gender = 'Female' THEN total_bill
        ELSE 0
    END) AS Female_Total_Bill,

    ROUND(
        SUM(CASE
            WHEN patient_gender = 'Male' THEN total_bill
            ELSE 0
        END)
        /
        NULLIF(
            SUM(CASE
                WHEN patient_gender = 'Female' THEN total_bill
                ELSE 0
            END),
            0
        ),
        2
    ) AS Male_Female_Bill_Ratio

FROM patient_complete_data
GROUP BY er_department_referral
ORDER BY er_department_referral;

-- 21.	Update the patient satisfaction score for all patients who visited the "General Practice" department and had a waiting time of more than 30 minutes. Increase their satisfaction score by 2 points, but ensure that the satisfaction score does not exceed 10. (SQL)
USE hospital_analytics;

UPDATE patient_complete_data
SET patient_sat_score = LEAST(patient_sat_score + 2, 10)
WHERE er_department_referral = 'General Practice'
  AND patient_waittime > 30;
